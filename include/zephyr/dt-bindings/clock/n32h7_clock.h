/*
 * An N32H7 clock gate is a bit in one of the RCC enable registers.  A clock
 * cell packs the register byte offset and the bit number:
 *
 *     ((offset) << 6) | (bit)
 *
 * The N32H7 has a separate set of enable registers per core, so each gate
 * has an N32H7_M7_CLOCK_* and an N32H7_M4_CLOCK_* form.  The devicetree for
 * a core uses the matching set; the devicetree preprocessor has no way to
 * know which core it is running for.
 */

#define N32H7_CLOCK_ID(offset, bit) (((offset) << 6) | (bit))

